%% =======================
% FUNCTION 1:
% MPP Residual Function
% =======================

function F = ...
    localResidual( ...
        Im, ...
        Vm, ...
        alpha, ...
        Is, ...
        Rs, ...
        Rsh)

    % --------------------------------------------------------
    % Diode exponential argument
    % --------------------------------------------------------

    arg = ...
        alpha ...
        * ...
        (Vm + Im*Rs);


    % --------------------------------------------------------
    % Prevent exponential overflow
    % --------------------------------------------------------

    arg = ...
        min( ...
            arg, ...
            700);


    exp_term = ...
        exp(arg);


    % --------------------------------------------------------
    % Numerator
    % --------------------------------------------------------

    numerator = ...
        Vm ...
        * ...
        ( ...
            -Is*alpha*exp_term ...
            - 1/Rsh ...
        );


    % --------------------------------------------------------
    % Denominator
    % --------------------------------------------------------

    denominator = ...
        1 ...
        + Rs/Rsh ...
        + alpha*Is*Rs*exp_term;


    % --------------------------------------------------------
    % MPP residual equation
    % --------------------------------------------------------

    F = ...
        Im ...
        + numerator/denominator;

end


%% =======================
% FUNCTION 2:
% Bisection Solver
% =======================

function root = ...
    myBisection( ...
        F, ...
        a, ...
        b, ...
        tolI, ...
        tolF, ...
        maxIter)

    fa = ...
        F(a);

    fb = ...
        F(b);


    % --------------------------------------------------------
    % Check initial interval
    % --------------------------------------------------------

    if ...
        ~isfinite(fa) ...
        || ...
        ~isfinite(fb) ...
        || ...
        fa*fb > 0

        error( ...
            'Invalid bisection interval.');

    end


    % --------------------------------------------------------
    % Bisection iterations
    % --------------------------------------------------------

    for iter = 1:maxIter

        c = ...
            0.5 ...
            * ...
            (a+b);

        fc = ...
            F(c);


        % ----------------------------------------------------
        % Check function value
        % ----------------------------------------------------

        if ...
            ~isfinite(fc) ...
            || ...
            ~isreal(fc)

            error( ...
                'Invalid function value during bisection.');

        end


        % ----------------------------------------------------
        % Convergence check
        % ----------------------------------------------------

        if ...
            abs(fc) < tolF ...
            || ...
            abs(b-a) < tolI

            root = ...
                c;

            return;

        end


        % ----------------------------------------------------
        % Update interval
        % ----------------------------------------------------

        if fa*fc <= 0

            b  = c;
            fb = fc;

        else

            a  = c;
            fa = fc;

        end

    end


    % --------------------------------------------------------
    % Return final midpoint
    % --------------------------------------------------------

    root = ...
        0.5 ...
        * ...
        (a+b);

end


%% =======================
% FUNCTION 3:
% PV Voltage Model
% =======================

function V = ...
    Vpv_D6L305L3A_sub( ...
        Ipv, ...
        G, ...
        T, ...
        Rs, ...
        Rsh, ...
        A)

    tol = ...
        1e-6;

    maxIter = ...
        1000;


    %% ===================
    % PV Module Parameters
    % ===================

    Iscn = ...
        9.91;

    Vocn = ...
        39.71/3;

    Ns = ...
        20;


    % --------------------------------------------------------
    % Reverse-breakdown parameters
    % --------------------------------------------------------

    Vbd = ...
        -25;

    Isr = ...
        0.0997;

    Kr = ...
        0.0114;


    % --------------------------------------------------------
    % Temperature coefficients
    % --------------------------------------------------------

    Ki = ...
        0.00495;

    Kv_temp = ...
        -0.00224;


    % --------------------------------------------------------
    % Physical constants
    % --------------------------------------------------------

    k = ...
        1.380649e-23;

    q = ...
        1.602176634e-19;

    Gn = ...
        1000;


    %% ===================
    % Temperature
    % ===================

    Tk = ...
        T + 273.15;

    Tnk = ...
        298.15;


    %% ===================
    % Thermal Voltage
    % ===================

    aVt = ...
        Ns ...
        * A ...
        * k ...
        * Tk ...
        / q;


    %% ===================
    % Photocurrent
    % ===================

    Iph = ...
        ( ...
            Iscn ...
            * ...
            (Rs+Rsh) ...
            / Rsh ...
            + ...
            Ki ...
            * ...
            (Tk-Tnk) ...
        ) ...
        * ...
        (G/Gn);


    %% ===================
    % Diode Saturation Current
    % ===================

    expTerm = ...
        ( ...
            Vocn ...
            + ...
            Kv_temp ...
            * ...
            (Tk-Tnk) ...
        ) ...
        / aVt;


    Is = ...
        ( ...
            Iscn ...
            + ...
            Ki ...
            * ...
            (Tk-Tnk) ...
        ) ...
        / ...
        ( ...
            exp(expTerm) ...
            - 1 ...
        );


    %% ===================
    % Initial Diode Voltage
    % ===================

    Vd = ...
        Vocn ...
        * ...
        ones(size(Ipv));


    converged = ...
        false;


    %% ===================
    % Newton-Raphson Solver
    % ===================

    for iter = 1:maxIter


        % ----------------------------------------------------
        % Exponential terms
        % ----------------------------------------------------

        expF = ...
            exp( ...
                min( ...
                    Vd./aVt, ...
                    700));


        expR = ...
            exp( ...
                min( ...
                    -Kr.*Vd./aVt, ...
                    700));


        % ----------------------------------------------------
        % Forward diode current
        % ----------------------------------------------------

        Idf = ...
            Is ...
            .* ...
            (expF-1);


        % ----------------------------------------------------
        % Reverse diode current
        % ----------------------------------------------------

        Idr = ...
            Isr ...
            .* ...
            exp( ...
                Kr ...
                .* ...
                Vbd ...
                ./ ...
                aVt) ...
            .* ...
            (expR-1);


        % ----------------------------------------------------
        % Shunt resistance current
        % ----------------------------------------------------

        Irsh = ...
            Vd ...
            ./ ...
            Rsh;


        % ----------------------------------------------------
        % Residual
        % ----------------------------------------------------

        y = ...
            Iph ...
            - Idf ...
            + Idr ...
            - Irsh ...
            - Ipv;


        % ----------------------------------------------------
        % Convergence check
        % ----------------------------------------------------

        if ...
            max(abs(y)) ...
            <= ...
            tol

            converged = ...
                true;

            break;

        end


        % ----------------------------------------------------
        % Derivative of forward diode current
        % ----------------------------------------------------

        dIdf = ...
            Is ...
            ./ ...
            aVt ...
            .* ...
            expF;


        % ----------------------------------------------------
        % Derivative of reverse diode current
        % ----------------------------------------------------

        dIdr = ...
            -Kr ...
            .* ...
            Isr ...
            ./ ...
            aVt ...
            .* ...
            exp( ...
                Kr ...
                .* ...
                Vbd ...
                ./ ...
                aVt) ...
            .* ...
            expR;


        % ----------------------------------------------------
        % Residual derivative
        % ----------------------------------------------------

        dy = ...
            -dIdf ...
            + dIdr ...
            - 1/Rsh;


        % ----------------------------------------------------
        % Newton step
        % ----------------------------------------------------

        step = ...
            y ...
            ./ ...
            dy;


        % ----------------------------------------------------
        % Limit Newton step
        % for numerical stability
        % ----------------------------------------------------

        step = ...
            max( ...
                min( ...
                    step, ...
                    1), ...
                -1);


        % ----------------------------------------------------
        % Update diode voltage
        % ----------------------------------------------------

        Vd = ...
            Vd ...
            - ...
            step;


        % ----------------------------------------------------
        % Limit internal diode voltage
        % ----------------------------------------------------

        Vd = ...
            max( ...
                min( ...
                    Vd, ...
                    Ns), ...
                -50);

    end


    %% ===================
    % Convergence Warning
    % ===================

    if ~converged

        warning( ...
            'PV model did not fully converge.');

    end


    %% ===================
    % Terminal PV Voltage
    % ===================
    %
    % V_terminal = V_diode - I*Rs
    %

    V = ...
        Vd ...
        - ...
        Ipv ...
        .* ...
        Rs;

end